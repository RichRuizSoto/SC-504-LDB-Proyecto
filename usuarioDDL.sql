-- Cuatro SP
CREATE OR REPLACE PROCEDURE sp_crear_empresa (
    p_nombre            IN empresas.nombre%TYPE,
    p_cedula_juridica   IN empresas.cedula_juridica%TYPE,
    p_direccion         IN empresas.direccion%TYPE,
    p_telefono          IN empresas.telefono%TYPE,
    p_email             IN empresas.email%TYPE,
    o_id_empresa        OUT NUMBER
)
AS
BEGIN
    INSERT INTO empresas (nombre, cedula_juridica, direccion, telefono, email)
    VALUES (p_nombre, p_cedula_juridica, p_direccion, p_telefono, p_email)
    RETURNING id_empresa INTO o_id_empresa;
END sp_crear_empresa;
/



CREATE OR REPLACE PROCEDURE sp_crear_usuario (
    p_nombre       IN usuarios.nombre%TYPE,
    p_usuario      IN usuarios.usuario%TYPE,
    p_email        IN usuarios.email%TYPE,
    p_telefono     IN usuarios.telefono%TYPE,
    p_hash         IN usuarios.contrasena_hash%TYPE,
    o_id_usuario   OUT NUMBER
)
AS
BEGIN
    INSERT INTO usuarios (nombre, usuario, email, telefono, contrasena_hash, estado)
    VALUES (p_nombre, p_usuario, p_email, p_telefono, p_hash, 1)
    RETURNING id_usuario INTO o_id_usuario;
END sp_crear_usuario;
/



CREATE OR REPLACE PROCEDURE sp_get_rol_admin (
    o_id_rol OUT NUMBER
)
AS
BEGIN
    SELECT id_rol INTO o_id_rol
    FROM roles
    WHERE nombre_rol = 'vendedor'
      AND estado = 1;
END sp_get_rol_admin;
/


CREATE OR REPLACE PROCEDURE sp_asignar_usuario_empresa (
    p_id_usuario    IN usuarios_empresas.id_usuario%TYPE,
    p_id_empresa    IN usuarios_empresas.id_empresa%TYPE,
    p_id_rol        IN usuarios_empresas.id_rol%TYPE
)
AS
BEGIN
    INSERT INTO usuarios_empresas (id_usuario, id_empresa, id_rol, fecha_asignacion)
    VALUES (p_id_usuario, p_id_empresa, p_id_rol, SYSDATE);
END sp_asignar_usuario_empresa;
/
