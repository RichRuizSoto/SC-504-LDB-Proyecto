--FUNCIONES--
--OBTENER STOCK DISPONIBLE DE UN PRODUCTO--
CREATE OR REPLACE FUNCTION fn_get_stock_producto(
    p_id_producto IN NUMBER
) RETURN NUMBER IS
    v_stock NUMBER;
BEGIN
    SELECT stock INTO v_stock
    FROM productos
    WHERE id_producto = p_id_producto AND estado = 'A';
    
    RETURN v_stock;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END;

--OBTENER EL PRECIO DE VENTA DE UN PRODUCTO--
CREATE OR REPLACE FUNCTION fn_get_precio_producto(
    p_id_producto IN NUMBER
) RETURN NUMBER IS
    v_precio NUMBER;
BEGIN
    SELECT precio_venta INTO v_precio
    FROM productos
    WHERE id_producto = p_id_producto AND estado = 'A';
    
    RETURN v_precio;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END;

--CALCULAR DESCUENTO DE UN PRODUCTO--
CREATE OR REPLACE FUNCTION fn_calcular_descuento(
    p_id_producto IN NUMBER,
    p_cantidad IN NUMBER,
    p_precio_unitario IN NUMBER
) RETURN NUMBER IS
    v_descuento NUMBER := 0;
    v_tipo VARCHAR2(20);
    v_valor NUMBER;
BEGIN
    SELECT tipo_descuento, valor_descuento
    INTO v_tipo, v_valor
    FROM descuentos
    WHERE id_producto = p_id_producto
      AND estado = 'A'
      AND (fecha_inicio IS NULL OR fecha_inicio <= SYSDATE)
      AND (fecha_fin IS NULL OR fecha_fin >= SYSDATE)
      AND ROWNUM = 1;
    
    IF v_tipo = 'PORCENTAJE' THEN
        v_descuento := (p_cantidad * p_precio_unitario * v_valor) / 100;
    ELSIF v_tipo = 'FIJO' THEN
        v_descuento := v_valor * p_cantidad;
    END IF;
    
    RETURN v_descuento;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END;

--VALIDAR SI UN PRODUCTO EXISTE Y ESTA ACTIVO--
CREATE OR REPLACE FUNCTION fn_validar_producto(
    p_id_producto IN NUMBER
) RETURN NUMBER IS
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM productos
    WHERE id_producto = p_id_producto AND estado = 'A';
    
    RETURN v_count;
END;

--OBTENER NOMBRE DE UN PRODUCTO--
CREATE OR REPLACE FUNCTION fn_get_nombre_producto(
    p_id_producto IN NUMBER
) RETURN VARCHAR2 IS
    v_nombre VARCHAR2(150);
BEGIN
    SELECT nombre_producto INTO v_nombre
    FROM productos
    WHERE id_producto = p_id_producto;
    
    RETURN v_nombre;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'Producto no encontrado';
END;
