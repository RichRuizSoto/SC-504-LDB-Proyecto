--PROCEDIMIENTOS--
--LISTAR PRODUCTOS DISPONIBLES--
CREATE OR REPLACE PROCEDURE sp_listar_productos_disponibles(
    p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN p_cursor FOR
        SELECT 
            p.id_producto,
            p.codigo_producto,
            p.nombre_producto,
            p.descripcion,
            p.precio_venta,
            p.stock,
            p.unidad_medida,
            c.nombre_categoria,
            prov.nombre_proveedor
        FROM productos p
        INNER JOIN categoria_producto c ON p.id_categoria = c.id_categoria
        LEFT JOIN proveedores prov ON p.id_proveedor = prov.id_proveedor
        WHERE p.estado = 'A' AND p.stock > 0
        ORDER BY p.nombre_producto;
END;

--BUSCAR PRODUCTOS POR NOMBRE--
CREATE OR REPLACE PROCEDURE sp_buscar_productos(
    p_nombre IN VARCHAR2,
    p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN p_cursor FOR
        SELECT 
            p.id_producto,
            p.codigo_producto,
            p.nombre_producto,
            p.descripcion,
            p.precio_venta,
            p.stock,
            p.unidad_medida
        FROM productos p
        WHERE p.estado = 'A' 
          AND UPPER(p.nombre_producto) LIKE '%' || UPPER(p_nombre) || '%'
        ORDER BY p.nombre_producto;
END;

--INICIAR UNA VENTA--
CREATE OR REPLACE PROCEDURE sp_iniciar_venta(
    p_id_usuario IN NUMBER,
    p_id_cliente IN NUMBER,
    p_id_metodo_pago IN NUMBER,
    p_id_venta OUT NUMBER
) AS
BEGIN
    INSERT INTO ventas (
        id_usuario,
        id_cliente,
        id_metodo_pago,
        fecha_venta,
        estado
    ) VALUES (
        p_id_usuario,
        p_id_cliente,
        p_id_metodo_pago,
        SYSTIMESTAMP,
        'EN_PROCESO'
    ) RETURNING id_venta INTO p_id_venta;
    
    COMMIT;
END;

--AGREGAR DETALLES A UNA VENTA--
CREATE OR REPLACE PROCEDURE sp_agregar_detalle_venta(
    p_id_venta IN NUMBER,
    p_id_producto IN NUMBER,
    p_cantidad IN NUMBER,
    p_id_detalle OUT NUMBER
) AS
    v_precio NUMBER;
    v_descuento NUMBER;
    v_stock NUMBER;
BEGIN
    -- Validar stock
    v_stock := fn_get_stock_producto(p_id_producto);
    IF v_stock < p_cantidad THEN
        RAISE_APPLICATION_ERROR(-20100, 'Stock insuficiente');
    END IF;
    
    -- Obtener precio
    v_precio := fn_get_precio_producto(p_id_producto);
    
    -- Calcular descuento
    v_descuento := fn_calcular_descuento(p_id_producto, p_cantidad, v_precio);
    
    -- Insertar detalle
    INSERT INTO detalle_ventas (
        id_venta,
        id_producto,
        cantidad,
        precio_unitario,
        descuento_unitario,
        impuesto
    ) VALUES (
        p_id_venta,
        p_id_producto,
        p_cantidad,
        v_precio,
        v_descuento / p_cantidad,
        (v_precio * p_cantidad - v_descuento) * 0.13  -- IVA 13%
    ) RETURNING id_detalle_venta INTO p_id_detalle;
    
    COMMIT;
END;

--FINALIZAR UNA VENTA--
CREATE OR REPLACE PROCEDURE sp_finalizar_venta(
    p_id_venta IN NUMBER,
    p_observacion IN VARCHAR2 DEFAULT NULL
) AS
    v_subtotal NUMBER := 0;
    v_descuento_total NUMBER := 0;
    v_impuesto_total NUMBER := 0;
    v_total NUMBER := 0;
    
    CURSOR cur_detalle IS
        SELECT cantidad, precio_unitario, descuento_unitario, impuesto
        FROM detalle_ventas
        WHERE id_venta = p_id_venta;
BEGIN
    -- Calcular totales usando cursor
    FOR det IN cur_detalle LOOP
        v_subtotal := v_subtotal + (det.cantidad * det.precio_unitario);
        v_descuento_total := v_descuento_total + det.descuento_unitario;
        v_impuesto_total := v_impuesto_total + det.impuesto;
    END LOOP;
    
    v_total := v_subtotal - v_descuento_total + v_impuesto_total;
    
    -- Actualizar venta
    UPDATE ventas
    SET subtotal = v_subtotal,
        descuento_total = v_descuento_total,
        impuesto = v_impuesto_total,
        total = v_total,
        estado = 'REGISTRADA',
        observacion = p_observacion
    WHERE id_venta = p_id_venta;
    
    COMMIT;
END;

--CANCELAR UNA VENTA--
CREATE OR REPLACE PROCEDURE sp_cancelar_venta(
    p_id_venta IN NUMBER,
    p_motivo IN VARCHAR2
) AS
BEGIN
    UPDATE ventas
    SET estado = 'CANCELADA',
        observacion = p_motivo
    WHERE id_venta = p_id_venta;
    
    -- Restaurar stock
    UPDATE productos p
    SET stock = stock + (
        SELECT SUM(dv.cantidad)
        FROM detalle_ventas dv
        WHERE dv.id_venta = p_id_venta
          AND dv.id_producto = p.id_producto
    )
    WHERE id_producto IN (
        SELECT id_producto 
        FROM detalle_ventas 
        WHERE id_venta = p_id_venta
    );
    
    COMMIT;
END;

--OBTENER HISTORIAL DE VENTAS--
CREATE OR REPLACE PROCEDURE sp_historial_ventas(
    p_fecha_inicio IN DATE DEFAULT NULL,
    p_fecha_fin IN DATE DEFAULT NULL,
    p_id_usuario IN NUMBER DEFAULT NULL,
    p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN p_cursor FOR
        SELECT 
            v.id_venta,
            v.codigo_venta,
            v.fecha_venta,
            u.nombre AS nombre_usuario,
            c.nombre_cliente,
            mp.nombre_metodo AS metodo_pago,
            v.subtotal,
            v.descuento_total,
            v.impuesto,
            v.total,
            v.estado
        FROM ventas v
        INNER JOIN usuarios u ON v.id_usuario = u.id_usuario
        LEFT JOIN clientes c ON v.id_cliente = c.id_cliente
        LEFT JOIN metodos_pago mp ON v.id_metodo_pago = mp.id_metodo_pago
        WHERE (p_fecha_inicio IS NULL OR TRUNC(v.fecha_venta) >= p_fecha_inicio)
          AND (p_fecha_fin IS NULL OR TRUNC(v.fecha_venta) <= p_fecha_fin)
          AND (p_id_usuario IS NULL OR v.id_usuario = p_id_usuario)
        ORDER BY v.fecha_venta DESC;
END;

