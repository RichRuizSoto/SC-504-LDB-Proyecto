--TRIGGERS--
--GENERAR CODIGO DE PRODUCTO--
CREATE OR REPLACE TRIGGER trg_prod_sku_bi
BEFORE INSERT ON productos
FOR EACH ROW
DECLARE
    v_cod VARCHAR2(6);
    v_num NUMBER;
BEGIN
    IF :new.codigo_producto IS NULL THEN
        SELECT codigo_categoria INTO v_cod
        FROM categoria_producto
        WHERE id_categoria = :new.id_categoria;
        
        v_num := cod_unico.nextval;
        :new.codigo_producto := 'ZHN-' || v_cod || '-' || LPAD(v_num, 5, '0');
    END IF;
END;

--GENERAR CODIGO VENTA--
CREATE OR REPLACE TRIGGER trg_venta_codigo_bi 
BEFORE INSERT ON ventas
FOR EACH ROW
BEGIN
    IF :new.codigo_venta IS NULL THEN
        :new.codigo_venta := 'V' || TO_CHAR(seq_cod_venta.nextval, 'FM000000');
    END IF;
END;

--ACTUALIZAR STOCK AL FINALIZAR UNA VENTA--
CREATE OR REPLACE TRIGGER trg_venta_actualizar_stock
AFTER UPDATE OF estado ON ventas
FOR EACH ROW
WHEN (NEW.estado = 'REGISTRADA' AND OLD.estado = 'EN_PROCESO')
DECLARE
    CURSOR cur_productos IS
        SELECT id_producto, cantidad
        FROM detalle_ventas
        WHERE id_venta = :NEW.id_venta;
BEGIN
    FOR prod IN cur_productos LOOP
        UPDATE productos
        SET stock = stock - prod.cantidad,
            fecha_actualizacion = SYSTIMESTAMP
        WHERE id_producto = prod.id_producto;
        
        -- Registrar movimiento de inventario
        INSERT INTO movimientos_inventario (
            id_producto,
            tipo_movimiento,
            cantidad,
            referencia,
            motivo,
            stock_anterior,
            stock_nuevo
        ) VALUES (
            prod.id_producto,
            'S',
            prod.cantidad,
            'VENTA-' || :NEW.codigo_venta,
            'Venta registrada',
            fn_get_stock_producto(prod.id_producto) + prod.cantidad,
            fn_get_stock_producto(prod.id_producto)
        );
    END LOOP;
END;

--VERIFICAR STOCK ANTES DE AGREGAR UN DETALLE--
CREATE OR REPLACE TRIGGER trg_validar_stock_detalle
BEFORE INSERT ON detalle_ventas
FOR EACH ROW
DECLARE
    v_stock NUMBER;
BEGIN
    v_stock := fn_get_stock_producto(:NEW.id_producto);
    
    IF v_stock < :NEW.cantidad THEN
        RAISE_APPLICATION_ERROR(-20101, 
            'Stock insuficiente. Disponible: ' || v_stock);
    END IF;
END;
