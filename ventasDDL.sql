--VISTAS--
--VENTAS DEL DIA--
CREATE OR REPLACE VIEW v_ventas_hoy AS
SELECT 
    v.id_venta,
    v.codigo_venta,
    v.fecha_venta,
    u.nombre AS vendedor,
    c.nombre_cliente,
    v.total,
    v.estado
FROM ventas v
INNER JOIN usuarios u ON v.id_usuario = u.id_usuario
LEFT JOIN clientes c ON v.id_cliente = c.id_cliente
WHERE TRUNC(v.fecha_venta) = TRUNC(SYSDATE);

--PRODUCTOS MAS VENDIDOS--
CREATE OR REPLACE VIEW v_productos_mas_vendidos AS
SELECT 
    p.id_producto,
    p.codigo_producto,
    p.nombre_producto,
    SUM(dv.cantidad) AS total_vendido,
    SUM(dv.total_linea) AS ingreso_total
FROM productos p
INNER JOIN detalle_ventas dv ON p.id_producto = dv.id_producto
INNER JOIN ventas v ON dv.id_venta = v.id_venta
WHERE v.estado = 'REGISTRADA'
GROUP BY p.id_producto, p.codigo_producto, p.nombre_producto
ORDER BY total_vendido DESC;

--RESUMEN DE VENTAS POR VENDEDOR--
CREATE OR REPLACE VIEW v_ventas_por_vendedor AS
SELECT 
    u.id_usuario,
    u.nombre AS vendedor,
    COUNT(v.id_venta) AS total_ventas,
    SUM(v.total) AS monto_total,
    AVG(v.total) AS promedio_venta
FROM usuarios u
INNER JOIN ventas v ON u.id_usuario = v.id_usuario
WHERE v.estado = 'REGISTRADA'
GROUP BY u.id_usuario, u.nombre;

--PRODUCTOS CON STOCK BAJO--
CREATE OR REPLACE VIEW v_stock_bajo AS
SELECT 
    p.id_producto,
    p.codigo_producto,
    p.nombre_producto,
    p.stock,
    c.nombre_categoria
FROM productos p
INNER JOIN categoria_producto c ON p.id_categoria = c.id_categoria
WHERE p.stock < 10 AND p.estado = 'A'
ORDER BY p.stock;

--METODOS DE PAGO--
CREATE OR REPLACE VIEW v_ventas_por_metodo_pago AS
SELECT 
    mp.nombre_metodo,
    COUNT(v.id_venta) AS cantidad_ventas,
    SUM(v.total) AS total_vendido
FROM metodos_pago mp
LEFT JOIN ventas v ON mp.id_metodo_pago = v.id_metodo_pago
WHERE v.estado = 'REGISTRADA'
GROUP BY mp.nombre_metodo;
